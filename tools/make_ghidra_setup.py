#!/usr/bin/env python3
"""Prepare the H8 ROM for Ghidra (H8/300H advanced mode, shizmob/ghidra-h8-300 module).

Usage: py tools/make_ghidra_setup.py [--set korgpro20]

Writes (firmware-derived, under data/analysis/):
  ic22_<ver>_cpu.bin      CPU byte order (un-word-swapped), first 256 KiB = visible ROM window
  ghidra_setup_ic22.py    GhidraScript (Jython or PyGhidra): memory map, vector/IO/table labels,
                          functions at every entry found by reference/h8dasm (FUNC lines)
Import the .bin as Raw Binary, language h8_300h:BE:32:advanced, base address 0, then run the script.
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent

KNOWN = {
    0x010932: "idle_loop",
    0x010036: "param_coef_table",      # 229 x {u8 dsp, u8 coef_addr, u32 compute_fn}
    0x018252: "param_dispatch",
    0x019e0a: "dsp_cload_write",
    0x01a2d2: "dsp_buffer_lookup",
    0x01a2f4: "dsp_send_dma",
    0x01a40e: "dsp_send_osc_program",
    0x01a48e: "dsp_send_fixed_buffer",
    0x01a520: "dsp_boot_load",
    0x019eb0: "dsp_mute_on_if",
    0x019ed8: "dsp_mute_off_if",
    0x01a28a: "osc_program_table",
    0x01a2ba: "fx_program_table",
    0x01a2c2: "dsp_table_by_index",
    0x019dfa: "dsp_port_by_index",
}
IO = {0x0fffd3: "PADR", 0x0fffd7: "PCDR", 0x0fff20: "DMA_MAR0A", 0x0fff24: "DMA_ETCR0A",
      0x0fff27: "DMA_DTCR0A", 0x0fff28: "DMA_MAR0B", 0x0fff2f: "DMA_DTCR0B", 0x0c0000: "DSP_PORT"}
VEC = {0: "reset", 7: "nmi", 11: "trapa3", 13: "irq1", 20: "wovi_tick", 52: "sci0_eri", 53: "sci0_rxi",
       54: "sci0_txi", 61: "vec61"}

SCRIPT = '''# Ghidra setup for the Prophecy H8 ROM (generated by tools/make_ghidra_setup.py).
# @category Prophecy
from ghidra.program.model.symbol import SourceType
mem = currentProgram.getMemory()
def block(name, start, size):
    try:
        mem.createUninitializedBlock(name, toAddr(start), size, False)
    except Exception as e:
        print("block %%s: %%s" %% (name, e))
block("SRAM", 0x040000, 0x20000)
block("SRAM_MIRROR", 0x060000, 0x20000)
block("DSP_PORT", 0x0c0000, 0x8)
block("ONCHIP_RAM", 0x0ffd10, 0x200)
block("IO", 0x0fff10, 0xf0)
def label(a, n):
    try:
        createLabel(toAddr(a), n, True, SourceType.USER_DEFINED)
    except Exception as e:
        print("label %%x: %%s" %% (a, e))
for a, n in %(io)s:
    label(a, n)
for v in range(64):
    createDWord(toAddr(v * 4))
for a, n in %(vec)s:
    label(a, n)
for a in %(funcs)s:
    disassemble(toAddr(a))
    if getFunctionAt(toAddr(a)) is None:
        createFunction(toAddr(a), None)
for a, n in %(known)s:
    f = getFunctionAt(toAddr(a))
    if f is not None:
        f.setName(n, SourceType.USER_DEFINED)
    else:
        label(a, n)
for a in %(coef_fns)s:
    disassemble(toAddr(a))
    f = getFunctionAt(toAddr(a)) or createFunction(toAddr(a), None)
    if f is not None and f.getName().startswith("FUN_"):
        f.setName("coef_fn_%%06x" %% a, SourceType.USER_DEFINED)
print("Prophecy H8 setup done")
'''


JAVA = '''// Ghidra setup for the Prophecy H8 ROM (generated by tools/make_ghidra_setup.py).
//@category Prophecy
import ghidra.app.script.GhidraScript;
import ghidra.program.model.mem.Memory;
import ghidra.program.model.symbol.SourceType;
import ghidra.program.model.listing.Function;

public class KpH8Setup extends GhidraScript {
	private void block(Memory mem, String name, long start, long size) {
		try { mem.createUninitializedBlock(name, toAddr(start), size, false); }
		catch (Exception e) { println("block " + name + ": " + e.getMessage()); }
	}
	private void label(long a, String n) {
		try { createLabel(toAddr(a), n, true, SourceType.USER_DEFINED); }
		catch (Exception e) { println("label " + Long.toHexString(a) + ": " + e.getMessage()); }
	}
	private Function func(long a) throws Exception {
		disassemble(toAddr(a));
		Function f = getFunctionAt(toAddr(a));
		return f != null ? f : createFunction(toAddr(a), null);
	}
	@Override
	public void run() throws Exception {
		Memory mem = currentProgram.getMemory();
		block(mem, "SRAM", 0x040000L, 0x20000L);
		block(mem, "SRAM_MIRROR", 0x060000L, 0x20000L);
		block(mem, "DSP_PORT", 0x0c0000L, 0x8L);
		block(mem, "ONCHIP_RAM", 0x0ffd10L, 0x200L);
		block(mem, "IO", 0x0fff10L, 0xf0L);
		for (int v = 0; v < 64; v++) { try { createDWord(toAddr(v * 4L)); } catch (Exception e) { } }
%(labels)s
		long[] funcs = { %(funcs)s };
		for (long a : funcs) { try { func(a); } catch (Exception e) { println("func " + Long.toHexString(a) + ": " + e.getMessage()); } }
		long[] coef = { %(coef)s };
		for (long a : coef) {
			try {
				Function f = func(a);
				if (f != null && f.getName().startsWith("FUN_")) f.setName(String.format("coef_fn_%%06x", a), SourceType.USER_DEFINED);
			} catch (Exception e) { println("coef " + Long.toHexString(a) + ": " + e.getMessage()); }
		}
%(names)s
		println("Prophecy H8 setup done: " + funcs.length + " functions, " + coef.length + " compute functions");
	}
}
'''


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--set", default="korgpro20")
    args = ap.parse_args()
    cfg = json.loads((REPO / "romdata" / f"{args.set}.json").read_text())
    rom = REPO / "data" / "roms" / args.set / cfg["ic22"]
    d = rom.read_bytes()
    cpu = bytearray(len(d))
    cpu[0::2], cpu[1::2] = d[1::2], d[0::2]
    out = REPO / "data" / "analysis"
    out.mkdir(parents=True, exist_ok=True)
    (out / f"{Path(cfg['ic22']).stem}_cpu.bin").write_bytes(bytes(cpu[:0x40000]))

    lst = out / f"{Path(cfg['ic22']).stem}.lst"
    funcs = sorted({int(m.group(1), 16) for m in re.finditer(r"^FUNC ([0-9a-f]{6})", lst.read_text(), re.M)}) if lst.exists() else []
    vec = []
    for v, n in VEC.items():
        t = int.from_bytes(cpu[v * 4:v * 4 + 4], "big") & 0xFFFFFF
        vec.append((t, f"vec{v}_{n}"))
    coef = sorted({int.from_bytes(cpu[0x010036 + 6 * i + 2:0x010036 + 6 * i + 6], "big") for i in range(229)})
    script = SCRIPT % {
        "io": repr(sorted(IO.items())),
        "vec": repr(vec),
        "funcs": repr(funcs),
        "known": repr(sorted(KNOWN.items())),
        "coef_fns": repr(coef),
    }
    (out / "ghidra_setup_ic22.py").write_text(script)
    labels = "\n".join(f'\t\tlabel(0x{a:06x}L, "{n}");' for a, n in sorted(IO.items()) + vec)
    names = "\n".join(
        f'\t\t{{ Function f = getFunctionAt(toAddr(0x{a:06x}L)); if (f != null) f.setName("{n}", SourceType.USER_DEFINED); else label(0x{a:06x}L, "{n}"); }}'
        for a, n in sorted(KNOWN.items()))
    java = JAVA % {
        "labels": labels,
        "funcs": ", ".join(f"0x{a:06x}L" for a in funcs),
        "coef": ", ".join(f"0x{a:06x}L" for a in coef),
        "names": names,
    }
    (out / "KpH8Setup.java").write_text(java)
    print(f"wrote {out / (Path(cfg['ic22']).stem + '_cpu.bin')} (256 KiB) and {out / 'ghidra_setup_ic22.py'}: "
          f"{len(funcs)} functions, {len(coef)} compute functions, {len(KNOWN)} names")
    return 0


if __name__ == "__main__":
    sys.exit(main())
