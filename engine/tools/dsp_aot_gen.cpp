// dsp_aot_gen: compile the firmware's DSP programs ahead of time (see engine/src/dsp_fast.h).
//
//   dsp_aot_gen <data dir> <out .inc> [--quick]
//
// Plays every program of the data dir (the user's ROM-derived engine data) through kp::Synth
// with notes and controllers, harvests each DSP's decode cache (one step per hash node: pc + ST1
// decode key -> op chain -> chained successor) and writes C++ for every distinct DSP program:
// a frame function with one labelled step per hash node, calling the interpreter's own op
// functions with constant operands. The output is firmware-derived: keep it under generated/.
#include "dsp_fast.h"
#include "synth.h"

#include "emu.h"
#include <algorithm>
#include <array>
#include <cstdio>
#include <cstring>
#include <fstream>
#include <map>
#include <set>
#include <string>
#include <vector>

#define private public
#define protected public
#include "tms57002.h"
#undef private
#undef protected

namespace {

using D = tms57002_device;

struct Step
{
	std::vector<std::pair<std::uint16_t, std::uint8_t>> ops;   // incl. terminator (op < 4) last
	bool has_succ = false;
	std::uint32_t succ_key = 0;                                 // successor is (pc + 1, succ_key)
	bool operator==(const Step &o) const { return ops == o.ops && has_succ == o.has_succ && succ_key == o.succ_key; }
};

struct Program
{
	std::map<std::pair<int, std::uint32_t>, Step> steps;   // (pc, key) -> step
	std::set<std::string> where;                           // dsp numbers seen running it
	int conflicts = 0;
};

std::map<std::uint64_t, Program> g_programs;

void harvest(D &d, int dsp)
{
	if (!d.cache.hused)
		return;
	const std::uint64_t hash = d.jit_program_hash();
	Program &prog = g_programs[hash];
	prog.where.insert(std::to_string(dsp + 1));
	// chain head ipc -> (pc, key)
	std::map<int, std::pair<int, std::uint32_t>> head;
	for (int pc = 0; pc < 256; pc++)
		for (int h = d.cache.hashbase[pc]; h != -1; h = d.cache.hashnode[h].next)
			if (d.cache.hashnode[h].ipc >= 0)
				head[d.cache.hashnode[h].ipc] = { pc, d.cache.hashnode[h].st1 };
	for (const auto &[ipc0, pk] : head)
	{
		Step st;
		int ipc = ipc0;
		for (int guard = 0; guard < 64; guard++)
		{
			const D::icd &i = d.cache.inst[ipc];
			st.ops.push_back({ i.op, i.op < 4 ? std::uint8_t(0) : i.param });
			if (i.op < 4)
			{
				if (i.next >= 0)
				{
					const auto it = head.find(i.next);
					if (it == head.end() || it->second.first != ((pk.first + 1) & 0xff))
					{
						std::fprintf(stderr, "dsp%d pc %02x: chained successor is not a step head\n", dsp + 1, pk.first);
						return;
					}
					st.has_succ = true;
					st.succ_key = it->second.second;
				}
				break;
			}
			ipc = i.next;
			if (ipc < 0)
			{
				std::fprintf(stderr, "dsp%d pc %02x: chain without terminator\n", dsp + 1, pk.first);
				return;
			}
		}
		const auto ins = prog.steps.emplace(pk, st);
		if (!ins.second && !(ins.first->second == st))
			prog.conflicts++;
	}
}

void harvest_all(kp::Synth &s)
{
	for (int d = 0; d < 3; d++)
		harvest(s.board().device(d), d);
}

void render(kp::Synth &s, double seconds)
{
	static float l[480], r[480];
	for (int n = int(seconds * 100); n > 0; n--)
		s.render(l, r, 480);
}

std::string term_code(int op)
{
	switch (op & 3)
	{
	case 1: return "\t++ca;\n";
	case 2: return "\t++id;\n";
	case 3: return "\t++ca, ++id;\n";
	default: return "";
	}
}

bool emit(const std::string &path, D &names)
{
	std::string o;
	char b[512];
	o += "// Generated by engine/tools/dsp_aot_gen from your firmware's DSP programs. Do not edit, do not\n"
	     "// distribute (firmware-derived). Included by engine/src/dsp_core.cpp.\n\n";
	// One out-of-line instance per distinct op (used when steps call ops instead of inlining them).
	std::set<unsigned> distinct;
	for (const auto &kv : g_programs)
		for (const auto &st : kv.second.steps)
			for (const auto &op : st.second.ops)
				if (op.first >= 4)
					distinct.insert(op.first);
	for (unsigned op : distinct)
		o += "KP_OPFN(" + std::to_string(op) + ")\n";
	o += "\n";
	int pi = 0;
	std::vector<std::string> table;
	for (const auto &[hash, prog] : g_programs)
	{
		std::vector<std::pair<int, std::uint32_t>> keys;
		for (const auto &kv : prog.steps)
			keys.push_back(kv.first);
		std::map<std::pair<int, std::uint32_t>, int> index;
		for (int k = 0; k < int(keys.size()); k++)
			index[keys[k]] = k;
		if (int(keys.size()) > kp::DspFast::kMaxSteps)
		{
			std::fprintf(stderr, "program %016llx: %zu steps, skipped\n", (unsigned long long)hash, keys.size());
			continue;
		}
		std::string where;
		for (const auto &w : prog.where)
			where += (where.empty() ? "" : ",") + w;
		std::snprintf(b, sizeof b, "// program %d: hash %016llx, DSP %s, %zu steps\n", pi, (unsigned long long)hash, where.c_str(), keys.size());
		o += b;
		std::string ops = "const AotOp kOps" + std::to_string(pi) + "[] = {\n";
		std::string steps = "const AotStep kSteps" + std::to_string(pi) + "[] = {\n";
		// The coefficient-RAM mode (st1 CRM, which selects how a coefficient read is viewed): only
		// the scrm ops write it at run time, so in a program without them it stays what it was when
		// the frame started. When every step was decoded with the same mode, the frame function
		// fixes it (kp_crm; the head hands a frame entered in another mode to the interpreter);
		// otherwise kp_crm = -1 and each read takes the mode from st1.
		int crm = -2;
		for (const auto &key : keys)
		{
			const int c = int((key.second & D::jit_st1_crm()) >> D::ST1_CRM_SHIFT);
			crm = crm == -2 || crm == c ? c : -1;
			for (const auto &[op, param] : prog.steps.at(key).ops)
			{
				const char *m = op >= 4 ? names.jit_op_mnemonic(op) : nullptr;
				if (m && !std::strcmp(m, "scrm"))
					crm = -1;
			}
		}
		std::string fn = "KP_AOT_FN void run" + std::to_string(pi) + "(D &dv, DspFast &f)\n{\n\tconstexpr int kp_crm = " +
		                 std::to_string(crm < 0 ? -1 : crm) + ";\n\tKP_HEAD()\n";
		// Entry points (dispatch cases): where a frame starts (pc 0), where execution continues
		// after a lookup (the pc after a step without a chained successor, branch targets) and the
		// step an rptk repeats. Entering anywhere else hands the frame to the interpreter (exact,
		// only slower); keeping the entry set small keeps the compiled code linear.
		std::set<int> entry_pcs = { 0 };
		std::set<int> entry;
		for (int k = 0; k < int(keys.size()); k++)
		{
			const auto &[pc, key] = keys[k];
			const Step &st = prog.steps.at(keys[k]);
			if (!st.has_succ)
				entry_pcs.insert((pc + 1) & 0xff);
			for (const auto &[op, param] : st.ops)
			{
				const char *m = op >= 4 ? names.jit_op_mnemonic(op) : nullptr;
				if (!m)
					continue;
				if (!std::strcmp(m, "b") || !std::strcmp(m, "bgz") || !std::strcmp(m, "blz") || !std::strcmp(m, "bnz") || !std::strcmp(m, "bv"))
					entry_pcs.insert(param);
				if (!std::strcmp(m, "rptk") && st.has_succ)
					entry.insert(index.at({ (pc + 1) & 0xff, st.succ_key }));
			}
		}
		for (int k = 0; k < int(keys.size()); k++)
			if (entry_pcs.count(keys[k].first))
				entry.insert(k);
		// Steps whose epilogue must test the repeat / branch state (KP_POST; the others get KP_POSTF):
		// a step with an rptk (sets rptc_next) or a branch (sets S_BRANCH), and every step that can run
		// with a repeat count pending, i.e. any step at the pc after an rptk or at a branch target of a
		// step with an rptk. Of the ops only rptk writes rptc_next and only the five branches set
		// S_BRANCH (tms_regops.py bodies); nothing schedules a pre-transfer (a restored snapshot can
		// hold one: the frame head hands such a frame to the interpreter, as it does any frame
		// entered with the repeat / branch state set).
		std::set<int> after_rptk;
		std::vector<bool> checked(keys.size(), false);
		for (int k = 0; k < int(keys.size()); k++)
		{
			const auto &[pc, key] = keys[k];
			const Step &st = prog.steps.at(keys[k]);
			bool rptk = false;
			std::vector<int> targets;
			for (const auto &[op, param] : st.ops)
			{
				const char *m = op >= 4 ? names.jit_op_mnemonic(op) : nullptr;
				if (!m)
					continue;
				if (!std::strcmp(m, "rptk"))
					rptk = checked[k] = true;
				if (!std::strcmp(m, "b") || !std::strcmp(m, "bgz") || !std::strcmp(m, "blz") || !std::strcmp(m, "bnz") || !std::strcmp(m, "bv"))
				{
					checked[k] = true;
					targets.push_back(param);
				}
			}
			if (rptk)
			{
				after_rptk.insert((pc + 1) & 0xff);
				after_rptk.insert(targets.begin(), targets.end());
			}
		}
		int n_checked = 0;
		for (int k = 0; k < int(keys.size()); k++)
		{
			if (after_rptk.count(keys[k].first))
				checked[k] = true;
			n_checked += checked[k];
		}
		std::fprintf(stderr, "program %016llx: %zu steps, %d with the repeat / branch test\n", (unsigned long long)hash, keys.size(), n_checked);
		int op_first = 0;
		for (int k = 0; k < int(keys.size()); k++)
		{
			const auto &[pc, key] = keys[k];
			const Step &st = prog.steps.at(keys[k]);
			int succ = -1;
			if (st.has_succ)
			{
				const auto it = index.find({ (pc + 1) & 0xff, st.succ_key });
				if (it == index.end())
				{
					std::fprintf(stderr, "program %016llx pc %02x: successor not harvested\n", (unsigned long long)hash, pc);
					return false;
				}
				succ = it->second;
			}
			std::snprintf(b, sizeof b, "\t{ 0x%02x, 0x%08x, %d, %zu, %d },\n", pc, key, op_first, st.ops.size(), succ);
			steps += b;
			std::snprintf(b, sizeof b, "S%d: // pc %02x key %08x\n", k, pc, key);
			fn += b;
			if (checked[k])
			{
				std::snprintf(b, sizeof b, "\tKP_PC(0x%02x)\n", pc);
				fn += b;
			}
			fn += "\tKP_PRE()\n";
			bool idle = false;
			for (const auto &[op, param] : st.ops)
			{
				std::snprintf(b, sizeof b, "\t{ %u, 0x%02x },\n", op, param);
				ops += b;
				op_first++;
				if (op < 4)
				{
					if (!idle)
						fn += term_code(op);
					break;
				}
				if (!idle)
				{
					std::snprintf(b, sizeof b, "\tKP_OP(%u, 0x%02x)\n", op, param);
					fn += b;
					const char *m = names.jit_op_mnemonic(op);
					if (m && !std::strcmp(m, "idle"))
						idle = true;   // the interpreter leaves the chain once S_IDLE is set
				}
			}
			const int pcnext = (pc + 1) & 0xff;
			if (checked[k])
				std::snprintf(b, sizeof b, "\tKP_POST(%d, 0x%02x, %s)\n", k, pcnext, pcnext == 0 ? "sti |= D::S_IDLE;" : "");
			else
				std::snprintf(b, sizeof b, "\tKP_POSTF(%d, 0x%02x, %s, %d, %d)\n", k, pcnext, pcnext == 0 ? "sti |= D::S_IDLE;" : "",
				              int(entry.count(k) || pcnext < 2), int(idle || pcnext == 0));
			fn += b;
			if (succ < 0)
			{
				if (!checked[k])
				{
					std::snprintf(b, sizeof b, "\tKP_PC(0x%02x)\n", pcnext);
					fn += b;
				}
				fn += "\tgoto lookup;\n";
			}
			else if (succ != k + 1)
				fn += "\tgoto S" + std::to_string(succ) + ";\n";
		}
		fn += "\tKP_DISPATCH()\n";
		for (int k : entry)
			fn += "\tcase " + std::to_string(k) + ": goto S" + std::to_string(k) + ";\n";
		fn += "\tKP_SLOW(kSteps" + std::to_string(pi) + ")\n\tKP_TAIL()\n}\n\n";
		o += ops + "};\n" + steps + "};\n" + fn;
		std::snprintf(b, sizeof b, "\t{ 0x%016llxull, kSteps%d, %zu, kOps%d, run%d },\n", (unsigned long long)hash, pi, keys.size(), pi, pi);
		table.push_back(b);
		pi++;
	}
	o += "const AotProgram kAotProgramsTable[] = {\n";
	for (const auto &t : table)
		o += t;
	if (table.empty())
		o += "\t{ 0, nullptr, 0, nullptr, nullptr },\n";
	o += "};\nconst AotProgram *const kAotPrograms = kAotProgramsTable;\nconstexpr int kAotProgramCount = " + std::to_string(table.size()) + ";\n";
	std::ofstream f(path, std::ios::binary);
	f << o;
	return bool(f);
}

} // namespace

int main(int argc, char **argv)
{
	if (argc < 3)
	{
		std::fprintf(stderr, "usage: %s <data dir> <out .inc> [--quick]\n", argv[0]);
		return 2;
	}
	const bool quick = argc > 3 && !std::strcmp(argv[3], "--quick");
	kp::dsp_fast_enable(false);   // harvest the interpreter's own caches
	kp::Synth s;
	std::string err;
	if (!s.load(argv[1], err))
	{
		std::fprintf(stderr, "%s\n", err.c_str());
		return 2;
	}
	if (s.booted() && s.save_snapshot(argv[1]))   // no snapshot in the data: the native boot's, for the engine's later loads
		std::fprintf(stderr, "booted the firmware natively; wrote state.bin + ram.bin to %s\n", argv[1]);
	render(s, 0.5);
	harvest_all(s);
	const int n = quick ? std::min(4, s.program_count()) : s.program_count();
	for (int p = 0; p < n; p++)
	{
		s.program(p);
		for (int k = 0; k < 12; k++)   // every 50 ms: the clear program runs ~0.11 s mid-change
		{
			render(s, 0.05);
			harvest_all(s);
		}
		s.note_on(60, 100);
		render(s, 0.3);
		s.note_on(67, 60);
		s.midi_cc(1, 127);
		render(s, 0.3);
		harvest_all(s);
		s.pitch_bend(16383);
		s.aftertouch(127);
		render(s, 0.2);
		s.pitch_bend(0);
		render(s, 0.2);
		harvest_all(s);
		s.note_off(60);
		s.note_off(67);
		s.pitch_bend(8192);
		s.aftertouch(0);
		s.midi_cc(1, 0);
		render(s, 0.4);
		harvest_all(s);
		std::fprintf(stderr, "\rprogram %d/%d", p + 1, n);
	}
	std::fprintf(stderr, "\n");
	for (const auto &[hash, prog] : g_programs)
	{
		std::string where;
		for (const auto &w : prog.where)
			where += w;
		int ops = 0;
		for (const auto &kv : prog.steps)
			ops += int(kv.second.ops.size());
		std::printf("program %016llx dsp %s: %zu steps, %d ops, %d conflicts\n", (unsigned long long)hash, where.c_str(), prog.steps.size(), ops, prog.conflicts);
	}
	if (!emit(argv[2], s.board().device(0)))
		return 1;
	std::printf("wrote %s (%zu programs)\n", argv[2], g_programs.size());
	return 0;
}
